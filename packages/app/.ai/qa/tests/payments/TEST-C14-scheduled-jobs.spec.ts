// TEST-C14 (payments parity spec phase 11, REQ-C13, DD-C08, DD-C09, AC-C13; issue #301 E12-S11): the four scheduled
// jobs, each run through `mercato payments run-job` — the job command its worker dispatches — with `--now`.
// - Sweeps: `reconcile-checkouts` sweeps a `created` checkout the provider captured without an event (the booking is
//   checked in the server process, see below); an open campaign past its orders deadline is `closed` by
//   `close-order-campaigns`.
// - Reminders: switched off → nothing; one payer (Adam) with three overdue charges gets one message per run listing
//   all three with his payer code, by e-mail and in the app, on day +1, +8, +15 and +22, and `reminder_count` stops at
//   4; a rental charge in his name and a charge without a payer are never reminded.
// - Generation: nothing in the month in which migration B was applied (this run's month); in the next month nothing
//   before the generation day, one generation on it, none on a second run; a month generated by hand and undone is not
//   generated again; switched off → nothing; a generation day of 29 → 400.
// - `payments set-up-club` twice: six schedules for the club (#525 added the order-link purge, #531 the invariant
//   check), not twelve; the other tenant's schedules untouched.
// - #405: a sweep run that changed nothing writes no audit entry; a club time zone change moves the generation and the
//   reminders to the new zone (`payments:reregister-schedules`).
test.describe.configure({ timeout: 420_000 })

type JobRun = CodedBody & Record<string, unknown> & { now: string }
type GenerateRun = JobRun & {
  outcome: { due: boolean; period: string; reason?: string }
  summary: { id: string; period: string; created: number } | null
}
type RemindRun = JobRun & {
  switchedOff: boolean
  counts: { payers: number; reminded: number; charges: number; unreachable: number; failed: number }
}

const JOB_NAMES = [
  'payments:close-order-campaigns',
  'payments:generate-charges',
  'payments:overdue-reminders',
  'payments:purge-order-links',
  'payments:reconcile-checkouts',
  'payments:verify-invariants',
]

/** The schedules that run in the club's time zone. */
const ZONED_JOBS = ['payments:generate-charges', 'payments:overdue-reminders', 'payments:verify-invariants']

function runJob(club: Club, job: string, now?: string): JobRun {
  const result = mercato([
    'payments',
    'run-job',
    '--job',
    job,
    '--tenant',
    club.tenant.tenantId,
    '--org',
    club.tenant.organizationId,
    ...(now ? ['--now', now] : []),
  ]) as JobRun | null
  if (!result) throw new Error(`[internal] payments run-job ${job} printed no result`)
  return result
}

function addDays(date: string, days: number): string {
  return new Date(Date.parse(`${date}T12:00:00Z`) + days * 86_400_000).toISOString().slice(0, 10)
}

async function putSettings(request: APIRequestContext, admin: string, data: Record<string, unknown>) {
  const current = await call<{ updatedAt?: string | null }>(request, 'GET', '/api/payments/settings', admin)
  expect(current.status, JSON.stringify(current.body)).toBe(200)
  return call<CodedBody & Record<string, unknown>>(request, 'PUT', '/api/payments/settings', admin, {
    data,
    headers: current.body?.updatedAt ? { [OPTIMISTIC_LOCK_HEADER]: current.body.updatedAt } : {},
  })
}

async function addCharge(request: APIRequestContext, admin: string, data: Record<string, unknown>) {
  const created = await call<CodedBody & { chargeId?: string; payerMissing?: boolean }>(
    request,
    'POST',
    '/api/payments/charges',
    admin,
    { data },
  )
  expect(created.status, JSON.stringify(created.body)).toBe(201)
  return created.body as { chargeId: string; payerMissing: boolean }
}

async function account(request: APIRequestContext, club: Club, personId: string, email: string) {
  const created = await createAccount(request, club.adminToken, personId, email)
  expect(created.status, JSON.stringify(created.body)).toBe(201)
  const userId = String(created.body?.userId)
  club.extraUserIds.push(userId)
  return signInAs(request, club, userId, email)
}

async function reminderCounts(ids: string[]): Promise<Record<string, number>> {
  return withClient(async (client) => {
    const { rows } = await client.query<{ id: string; reminder_count: number }>(
      'select id, reminder_count from payments_charges where id = any($1::uuid[])',
      [ids],
    )
    return Object.fromEntries(rows.map((row) => [row.id, row.reminder_count]))
  })
}

/** A rental charge in the payer's name (payable to the facility owner), written as the rental charge service does. */
async function insertRentalCharge(club: Club, payerPersonId: string, dueDate: string): Promise<string> {
  return withClient(async (client) => {
    const { rows } = await client.query<{ id: string }>(
      `insert into payments_charges
         (id, tenant_id, organization_id, source_type, source_id, payer_person_id, description, amount, due_date,
          payee, status, created_at, updated_at)
       values (gen_random_uuid(), $1, $2, 'rental', gen_random_uuid(), $3, 'Wynajem boiska', 20000, $4,
          'owner_institution', 'open', now(), now())
       returning id`,
      [club.tenant.tenantId, club.tenant.organizationId, payerPersonId, dueDate],
    )
    return rows[0].id
  })
}

async function generationsOf(organizationId: string, period: string) {
  return withClient(async (client) => {
    const { rows } = await client.query<{ id: string; undone: boolean }>(
      `select id, undone_at is not null as undone from payments_charge_generations
        where organization_id = $1 and period = $2 and deleted_at is null`,
      [organizationId, period],
    )
    return rows
  })
}

/** The audit rows of the club's job runs (`action_logs` is encrypted at rest; only plain columns are matched). */
async function jobLogCount(organizationId: string): Promise<number> {
  return withClient(async (client) => {
    const { rows } = await client.query<{ count: string }>(
      `select count(*) as count from action_logs
        where resource_kind = 'payments.organization' and resource_id = $1 and deleted_at is null`,
      [organizationId],
    )
    return Number(rows[0].count)
  })
}

async function schedulesOf(organizationId: string) {
  return withClient(async (client) => {
    const { rows } = await client.query<{ name: string; schedule_value: string; timezone: string | null }>(
      `select name, schedule_value, timezone from scheduled_jobs
        where organization_id = $1 and name like 'payments:%' and deleted_at is null order by name`,
      [organizationId],
    )
    return rows
  })
}

test('TEST-C14 generation, overdue reminders and the two sweeps run on a schedule', async ({ request }) => {
  const club = await createClub(request, 'test-c14')
  const other = await createClub(request, 'test-c14-other')
  try {
    const admin = club.adminToken
    const today = calendarDate()

    // --- The checkout sweep: a capture without an event is booked by `reconcile-checkouts` ---
    const ewaEmail = uniqueAddress('ewa-c14')
    const ewa = await createPerson(request, admin, {
      firstName: 'Ewa',
      lastName: 'Płacąca',
      birthDate: birthDateTurning(35),
      email: ewaEmail,
    })
    // A guardian who pays for her ward holds `payments.pay_online` (the payer role comes with the guardianship).
    const zosia = await createPerson(request, admin, {
      firstName: 'Zosia',
      lastName: 'Płacąca',
      birthDate: birthDateTurning(8),
    })
    await createGuardianship(request, admin, {
      guardianPersonId: ewa,
      wardPersonId: zosia,
      relation: 'parent',
      isPrimaryPayer: true,
      validFrom: today,
    })
    const ewaToken = await account(request, club, ewa, ewaEmail)
    const ewaCharge = await addCharge(request, admin, {
      personId: zosia,
      payerPersonId: ewa,
      description: 'Opłata za obóz',
      amount: 5000,
      dueDate: calendarDate(30),
    })
    const started = await checkout(request, ewaToken, [ewaCharge.chargeId])
    await gatewayWebhook(request, {
      sessionId: started.sessionId,
      status: 'captured',
      amountReceived: 50,
      notify: false,
    })
    expect((await getCharge(request, admin, ewaCharge.chargeId)).status).toBe('open')
    // The job command sweeps the club's unfinished checkout. The test gateway keeps its sessions in the memory of the
    // server process, so the CLI process cannot see the capture; the booking itself is the same `fulfilCheckout` that
    // TEST-057 drives through the refresh in the server process, and the scheduled worker runs in that process.
    const reconciled = runJob(club, 'reconcile-checkouts') as JobRun & { summary: { checked: number } }
    expect(reconciled.summary.checked).toBeGreaterThanOrEqual(1)
    expect((await refreshCheckout(request, ewaToken, started.checkoutId)).body).toMatchObject({ status: 'completed' })
    expect(await getCharge(request, admin, ewaCharge.chargeId)).toMatchObject({ status: 'paid', paid: 5000 })

    // --- The campaign sweep: an open campaign past its orders deadline is closed ---
    const academy = await createStructure(request, admin, 'sections', { name: 'Akademia piłkarska' })
    const zaki = await createGroup(request, admin, { sectionId: academy, name: 'Żaki', kind: 'team' })
    const closesOn = calendarDate(3)
    const campaign = await postCampaign(request, admin, {
      name: 'Szaliki 2026',
      sectionId: academy,
      groupIds: [zaki],
      closesOn,
      paymentDueOn: calendarDate(10),
      products: [{ key: 'scarf', name: 'Szalik', priceChild: 3000 }],
    })
    expect(campaign.status, JSON.stringify(campaign.body)).toBe(201)
    const campaignId = String(campaign.body?.id)
    const opened = await transition(request, admin, campaignId, 'open', String(campaign.body?.updatedAt))
    expect(opened.status, JSON.stringify(opened.body)).toBe(200)
    // Only the run that closed something is audited; the empty run before it adds no `action_logs` row (#405).
    const jobLogsBefore = await jobLogCount(club.tenant.organizationId)
    expect((runJob(club, 'close-order-campaigns') as JobRun & { closed: string[] }).closed).not.toContain(campaignId)
    expect(await jobLogCount(club.tenant.organizationId)).toBe(jobLogsBefore)
    const swept = runJob(club, 'close-order-campaigns', zoneInstant(addDays(closesOn, 1), '00:15')) as JobRun & {
      closed: string[]
    }
    expect(swept.closed).toContain(campaignId)
    expect((await getCampaign(request, admin, campaignId)).status).toBe('closed')
    expect(await jobLogCount(club.tenant.organizationId)).toBe(jobLogsBefore + 1)

    // --- Overdue reminders: one payer, three charges; a rental charge and a charge without a payer never ---
    const adamEmail = uniqueAddress('adam-c14')
    const adam = await createPerson(request, admin, {
      firstName: 'Adam',
      lastName: 'Dorosły',
      birthDate: birthDateTurning(30),
      email: adamEmail,
    })
    const adamToken = await account(request, club, adam, adamEmail)
    const bartek = await createPerson(request, admin, {
      firstName: 'Bartek',
      lastName: 'Wolny',
      birthDate: birthDateTurning(9),
    })
    const due = calendarDate(2)
    const descriptions = ['Składka listopad', 'Turniej halowy', 'Badania lekarskie']
    const adamCharges: string[] = []
    for (const [index, description] of descriptions.entries()) {
      adamCharges.push(
        (await addCharge(request, admin, { personId: adam, description, amount: 4000 + index * 1000, dueDate: due }))
          .chargeId,
      )
    }
    const orphan = await addCharge(request, admin, {
      personId: bartek,
      description: 'Opłata bez płatnika',
      amount: 3000,
      dueDate: due,
    })
    expect(orphan.payerMissing).toBe(true)
    const rental = await insertRentalCharge(club, adam, due)
    const remind = (day: string) => runJob(club, 'overdue-reminders', zoneInstant(day, '09:00')) as RemindRun

    // Switched off: nothing is sent or marked.
    const off = await putSettings(request, admin, { overdueReminders: false })
    expect(off.status, JSON.stringify(off.body)).toBe(200)
    expect(off.body).toMatchObject({ overdueReminders: false, autoGenerateCharges: true, generationDay: 1 })
    expect(remind(addDays(due, 1))).toMatchObject({ switchedOff: true, counts: { reminded: 0 } })
    expect((await putSettings(request, admin, { overdueReminders: true })).status).toBe(200)

    // On the due date nothing; from the day after: day +1, +8, +15, +22, each one message with all three charges.
    expect(remind(due).counts).toMatchObject({ payers: 0, reminded: 0 })
    const reminderDays = [1, 8, 15, 22].map((offset) => addDays(due, offset))
    for (const [index, day] of reminderDays.entries()) {
      expect(remind(day).counts, day).toMatchObject({ payers: 1, reminded: 1, charges: 3, failed: 0 })
      // A second run on the same day sends nothing.
      expect(remind(day).counts, `${day} again`).toMatchObject({ payers: 0, reminded: 0 })
      const mails = await awaitEmails(adamEmail, 'Adam Dorosły', index + 1)
      const last = mails.at(-1)
      for (const description of descriptions) expect(last?.text).toContain(description)
      expect(last?.text).not.toContain('Wynajem boiska')
      expect(last?.text).toMatch(/GW-[A-Z0-9]{4}/)
    }
    // Between two reminders (day +9) and after the fourth (day +29) nothing more.
    expect(remind(addDays(due, 9)).counts).toMatchObject({ payers: 0 })
    expect(remind(addDays(due, 29)).counts).toMatchObject({ payers: 0, reminded: 0 })
    expect(emailsTo(adamEmail, 'Adam Dorosły')).toHaveLength(4)
    const counts = await reminderCounts([...adamCharges, orphan.chargeId, rental])
    expect(adamCharges.map((id) => counts[id])).toEqual([4, 4, 4])
    expect(counts[orphan.chargeId]).toBe(0)
    expect(counts[rental]).toBe(0)
    await expect
      .poll(
        async () =>
          (await readNotifications(request, adamToken)).filter((item) => item.type === 'payments.charge_overdue')
            .length,
        { timeout: 60_000 },
      )
      .toBeGreaterThanOrEqual(1)

    // Charges overdue on different days keep their own cadence (#404): the message lists every overdue charge, but
    // only the charges due a reminder count it. Adam's first three charges are capped, so they are no longer listed.
    const firstDue = addDays(due, 30)
    const secondDue = addDays(due, 33)
    const staggered = [
      (await addCharge(request, admin, { personId: adam, description: 'Obóz zimowy', amount: 9000, dueDate: firstDue }))
        .chargeId,
      (
        await addCharge(request, admin, {
          personId: adam,
          description: 'Strój klubowy',
          amount: 6000,
          dueDate: secondDue,
        })
      ).chargeId,
    ]
    expect(remind(addDays(firstDue, 1)).counts).toMatchObject({ payers: 1, reminded: 1, charges: 1, failed: 0 })
    expect(remind(addDays(secondDue, 1)).counts).toMatchObject({ payers: 1, reminded: 1, charges: 1, failed: 0 })
    const staggeredMails = await awaitEmails(adamEmail, 'Adam Dorosły', 6)
    expect(staggeredMails.at(-1)?.text).toContain('Obóz zimowy')
    expect(staggeredMails.at(-1)?.text).toContain('Strój klubowy')
    expect(Object.values(await reminderCounts(staggered))).toEqual([1, 1])
    // A week after its own first reminder the first charge is reminded again; the second waits for its own week.
    expect(remind(addDays(firstDue, 8)).counts).toMatchObject({ payers: 1, reminded: 1, charges: 1 })
    const afterWeek = await reminderCounts(staggered)
    expect(staggered.map((id) => afterWeek[id])).toEqual([2, 1])

    // --- Generation: never in migration B's month; in the next months on the generation day, once ---
    const anna = await createPerson(request, admin, {
      firstName: 'Anna',
      lastName: 'Nowak',
      birthDate: birthDateTurning(40),
    })
    const ola = await createPerson(request, admin, {
      firstName: 'Ola',
      lastName: 'Nowak',
      birthDate: birthDateTurning(10),
    })
    await createGuardianship(request, admin, {
      guardianPersonId: anna,
      wardPersonId: ola,
      relation: 'parent',
      isPrimaryPayer: true,
      validFrom: today,
    })
    await addMembership(request, admin, { groupId: zaki, personId: ola, role: 'participant', validFrom: today })
    await createFee(request, admin, {
      name: 'Żaki',
      groupId: zaki,
      period: 'monthly',
      amount: 15000,
      dueDay: 10,
      validFrom: today,
    })
    const orgId = club.tenant.organizationId
    const generateOn = (day: string) => runJob(club, 'generate-charges', zoneInstant(day, '06:00')) as GenerateRun

    // This run's month is the one migration B was applied in: nothing, even after its generation day.
    const thisMonth = periodFromNow(0)
    expect((runJob(club, 'generate-charges') as GenerateRun).outcome).toMatchObject({
      due: false,
      period: thisMonth,
      reason: 'before_first_month',
    })
    expect(await generationsOf(orgId, thisMonth)).toHaveLength(0)

    // A day outside 1–28 is refused; day 5 is kept.
    const invalidDay = await putSettings(request, admin, { generationDay: 29 })
    expect(invalidDay.status, JSON.stringify(invalidDay.body)).toBe(400)
    expect((await putSettings(request, admin, { generationDay: 5 })).body).toMatchObject({ generationDay: 5 })

    const nextMonth = periodFromNow(1)
    expect(generateOn(`${nextMonth}-04`).outcome).toMatchObject({ due: false, reason: 'before_day' })
    const generated = generateOn(`${nextMonth}-05`)
    expect(generated.outcome).toEqual({ due: true, period: nextMonth })
    expect(generated.summary).toMatchObject({ period: nextMonth, created: 1 })
    expect(generateOn(`${nextMonth}-05`).outcome).toMatchObject({ due: false, reason: 'generated' })
    expect(generateOn(`${nextMonth}-20`).outcome).toMatchObject({ due: false, reason: 'generated' })
    expect(await generationsOf(orgId, nextMonth)).toHaveLength(1)

    // A month generated by hand and undone is not generated again automatically.
    const laterMonth = periodFromNow(2)
    const manual = await generate(request, admin, laterMonth)
    expect(manual.status, JSON.stringify(manual.body)).toBe(200)
    const manualLog = (await actionLogEntries(request, admin, String(manual.body?.generationId))).find(
      (entry) => entry.commandId === 'payments.charges.generate',
    )
    const undone = await undoByToken(request, admin, String(manualLog?.undoToken))
    expect(undone.status(), await undone.text()).toBe(200)
    expect(generateOn(`${laterMonth}-05`).outcome).toMatchObject({ due: false, reason: 'generated' })
    expect(await generationsOf(orgId, laterMonth)).toEqual([expect.objectContaining({ undone: true })])

    // Switched off: nothing.
    expect((await putSettings(request, admin, { autoGenerateCharges: false })).status).toBe(200)
    const offMonth = periodFromNow(3)
    expect(generateOn(`${offMonth}-05`).outcome).toMatchObject({ due: false, reason: 'switched_off' })
    expect(await generationsOf(orgId, offMonth)).toHaveLength(0)

    // --- The schedules: six per club after two set-ups, the other tenant untouched ---
    const otherBefore = await schedulesOf(other.tenant.organizationId)
    const scope = ['--tenant', club.tenant.tenantId, '--org', orgId]
    for (let run = 0; run < 2; run += 1) {
      expect(mercato(['payments', 'set-up-club', ...scope])).toEqual({
        schedules: {
          'generate-charges': true,
          'overdue-reminders': true,
          'reconcile-checkouts': true,
          'close-order-campaigns': true,
          'purge-order-links': true,
          'verify-invariants': true,
        },
      })
    }
    const schedules = await schedulesOf(orgId)
    expect(schedules.map((row) => row.name)).toEqual(JOB_NAMES)
    expect(schedules.find((row) => row.name === 'payments:generate-charges')).toMatchObject({
      schedule_value: '0 6 * * *',
      timezone: 'Europe/Warsaw',
    })
    expect(schedules.find((row) => row.name === 'payments:overdue-reminders')?.schedule_value).toBe('0 9 * * *')
    expect(schedules.find((row) => row.name === 'payments:reconcile-checkouts')?.schedule_value).toBe('15m')
    expect(schedules.find((row) => row.name === 'payments:verify-invariants')).toMatchObject({
      schedule_value: '0 3 * * *',
      timezone: 'Europe/Warsaw',
    })
    expect(await schedulesOf(other.tenant.organizationId)).toEqual(otherBefore)

    // --- A time zone change re-registers the time-zoned schedules (#405) ---
    const clubSettings = await call<{ updatedAt?: string }>(request, 'GET', '/api/club_core/settings', admin)
    const moved = await call(request, 'PUT', '/api/club_core/settings', admin, {
      data: { timezone: 'Europe/Lisbon' },
      headers: clubSettings.body?.updatedAt ? { [OPTIMISTIC_LOCK_HEADER]: clubSettings.body.updatedAt } : {},
    })
    expect(moved.status, JSON.stringify(moved.body)).toBe(200)
    await expect
      .poll(
        async () =>
          (await schedulesOf(orgId))
            .filter((row) => ZONED_JOBS.includes(row.name))
            .map((row) => [row.name, row.timezone]),
        { timeout: 60_000 },
      )
      .toEqual([
        ['payments:generate-charges', 'Europe/Lisbon'],
        ['payments:overdue-reminders', 'Europe/Lisbon'],
        ['payments:verify-invariants', 'Europe/Lisbon'],
      ])
    expect((await schedulesOf(orgId)).map((row) => row.name)).toEqual(JOB_NAMES)
    expect(await schedulesOf(other.tenant.organizationId)).toEqual(otherBefore)
  } finally {
    await other.cleanup()
    await club.cleanup()
  }
})
