// Unit tests for the Enterprise overlay install (enterprise package spec DD-E02, DD-E11; ENT-TEST-05 of #713): the
// manifest patch, the lockfile-diff rule (only the Enterprise workspace entry and its app dependency line may change)
// and the `--ci` trust file. `yarn install` is replaced by a fake that writes the lockfile it would have written.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { test } from 'node:test'
import {
  APP_MANIFEST,
  CI_TRUST_FILE,
  ENTERPRISE_DIR,
  ENTERPRISE_PACKAGE,
  TEST_KEY_PAIR,
  checkEnterpriseManifest,
  ciTrustFile,
  linkPackagesNodeModules,
  lockfileProblems,
  main,
  parseArgs,
  parseLockfile,
  patchAppManifest,
  runYarnInstall,
} from '../../../../scripts/enterprise-overlay.mjs'

const APP_ENTRY = '"@vereino/app@workspace:packages/app":'
const ENTERPRISE_ENTRY = `"${ENTERPRISE_PACKAGE}@workspace:*, ${ENTERPRISE_PACKAGE}@workspace:packages/enterprise":`

const BEFORE = [
  '# This file is generated by running "yarn install" inside your project.',
  '',
  '__metadata:',
  '  version: 8',
  '',
  APP_ENTRY,
  '  version: 0.0.0-use.local',
  '  dependencies:',
  '    "@vereino/core": "workspace:*"',
  '    react: "npm:19.2.8"',
  '',
  '"react@npm:19.2.8":',
  '  version: 19.2.8',
  '',
].join('\n')

const ENTERPRISE_STANZA = [
  ENTERPRISE_ENTRY,
  '  version: 0.0.0-use.local',
  '  dependencies:',
  '    react: "npm:19.2.8"',
  '',
].join('\n')

const AFTER = BEFORE.replace(
  '    "@vereino/core": "workspace:*"\n',
  `    "@vereino/core": "workspace:*"\n    "${ENTERPRISE_PACKAGE}": "workspace:*"\n`,
).concat(ENTERPRISE_STANZA)

function tree({
  enterprise = { name: ENTERPRISE_PACKAGE, private: true },
  appDependencies = { react: '19.2.8' },
} = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'enterprise-overlay-'))
  const write = (relativePath, content) => {
    fs.mkdirSync(path.dirname(path.join(root, relativePath)), { recursive: true })
    fs.writeFileSync(path.join(root, relativePath), content)
  }
  if (enterprise) write(`${ENTERPRISE_DIR}/package.json`, JSON.stringify(enterprise))
  write(APP_MANIFEST, JSON.stringify({ name: '@vereino/app', dependencies: appDependencies }))
  write('yarn.lock', BEFORE)
  write(TEST_KEY_PAIR, JSON.stringify({ kid: 'test-2026-1', publicKeyPem: 'PUBLIC', privateKeyPem: 'PRIVATE' }))
  return root
}

function capture() {
  const out = []
  const err = []
  return { out, err, log: (line) => out.push(line), logError: (line) => err.push(line) }
}

const installWriting =
  (lockfile, status = 0) =>
  ({ rootDir }) => {
    fs.writeFileSync(path.join(rootDir, 'yarn.lock'), lockfile)
    return status
  }

test('parseArgs reads --root, --ci and --no-install and refuses anything else', () => {
  assert.deepEqual(parseArgs([]), { rootDir: process.cwd(), ci: false, install: true })
  assert.deepEqual(parseArgs(['--ci', '--no-install', '--root', 'x']), {
    rootDir: path.resolve('x'),
    ci: true,
    install: false,
  })
  assert.throws(() => parseArgs(['--root']), /Usage/)
  assert.throws(() => parseArgs(['--immutable']), /Usage/)
})

test('checkEnterpriseManifest wants the private package @vereino/enterprise', () => {
  assert.deepEqual(checkEnterpriseManifest({ name: ENTERPRISE_PACKAGE, private: true }), [])
  assert.deepEqual(checkEnterpriseManifest({ name: '@acme/x' }), [
    `${ENTERPRISE_DIR}/package.json names @acme/x, not ${ENTERPRISE_PACKAGE}`,
    `${ENTERPRISE_DIR}/package.json must be "private": true`,
  ])
})

test('patchAppManifest adds the workspace dependency once, sorted', () => {
  const first = patchAppManifest({ name: 'app', dependencies: { zod: '^4', '@vereino/core': 'workspace:*' } })
  assert.equal(first.changed, true)
  assert.deepEqual(Object.keys(first.manifest.dependencies), ['@vereino/core', ENTERPRISE_PACKAGE, 'zod'])
  assert.deepEqual(patchAppManifest(first.manifest), { manifest: first.manifest, changed: false })
  assert.deepEqual(patchAppManifest({ name: 'app' }).manifest.dependencies, { [ENTERPRISE_PACKAGE]: 'workspace:*' })
})

test('parseLockfile keys each entry by its first line', () => {
  const entries = parseLockfile(BEFORE)
  assert.deepEqual([...entries.keys()], ['__metadata:', APP_ENTRY, '"react@npm:19.2.8":'])
  assert.deepEqual(entries.get('"react@npm:19.2.8":'), ['  version: 19.2.8'])
  assert.equal(parseLockfile('  stray indented line\n').size, 0)
})

test('lockfileProblems accepts only the Enterprise entry and its app dependency line', () => {
  assert.deepEqual(lockfileProblems(BEFORE, AFTER), [])
  assert.deepEqual(lockfileProblems(BEFORE, BEFORE), [])
})

test('lockfileProblems names an added, changed or removed third-party resolution', () => {
  const added = `${AFTER}\n"left-pad@npm:1.3.0":\n  version: 1.3.0\n`
  assert.deepEqual(lockfileProblems(BEFORE, added), ['added resolution "left-pad@npm:1.3.0":'])
  const changed = AFTER.replace('  version: 19.2.8', '  version: 19.2.9')
  assert.deepEqual(lockfileProblems(BEFORE, changed), ['changed resolution "react@npm:19.2.8":'])
  const appChanged = AFTER.replace('    react: "npm:19.2.8"\n\n"react', '    react: "npm:19.2.9"\n\n"react')
  assert.deepEqual(lockfileProblems(BEFORE, appChanged), [`changed resolution ${APP_ENTRY}`])
  const removed = AFTER.replace('"react@npm:19.2.8":\n  version: 19.2.8\n', '')
  assert.deepEqual(lockfileProblems(BEFORE, removed), ['removed resolution "react@npm:19.2.8":'])
})

test('ciTrustFile holds the kid and the public key, never the private key', () => {
  const text = ciTrustFile({ kid: 'test-2026-1', publicKeyPem: 'PUBLIC', privateKeyPem: 'PRIVATE' })
  assert.deepEqual(JSON.parse(text), { 'test-2026-1': 'PUBLIC' })
  assert.doesNotMatch(text, /PRIVATE/)
})

test('main installs the overlay, checks the lockfile and writes the --ci trust file', () => {
  const root = tree()
  const io = capture()
  const code = main({ args: ['--root', root, '--ci'], ...io, runInstall: installWriting(AFTER) })
  assert.equal(code, 0, io.err.join('\n'))
  const manifest = JSON.parse(fs.readFileSync(path.join(root, APP_MANIFEST), 'utf8'))
  assert.equal(manifest.dependencies[ENTERPRISE_PACKAGE], 'workspace:*')
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(root, CI_TRUST_FILE), 'utf8')), { 'test-2026-1': 'PUBLIC' })
  assert.match(io.out.join('\n'), /added @vereino\/enterprise/)
  assert.match(io.out.join('\n'), /yarn\.lock: only the Enterprise workspace entry/)
})

test('main without --ci writes no trust file, and keeps an already patched manifest', () => {
  const root = tree({ appDependencies: { [ENTERPRISE_PACKAGE]: 'workspace:*' } })
  const io = capture()
  assert.equal(main({ args: ['--root', root, '--no-install'], ...io }), 0)
  assert.equal(fs.existsSync(path.join(root, CI_TRUST_FILE)), false)
  assert.match(io.out[0], /^kept /)
})

test('main fails without the package, with a wrong package, on a failed install and on a changed resolution', () => {
  const missing = capture()
  assert.equal(main({ args: ['--root', tree({ enterprise: null })], ...missing }), 1)
  assert.match(missing.err[0], /packages\/enterprise\/package\.json is missing/)

  const wrong = capture()
  assert.equal(main({ args: ['--root', tree({ enterprise: { name: '@acme/x', private: true } })], ...wrong }), 1)
  assert.match(wrong.err[0], /names @acme\/x/)

  const failed = capture()
  assert.equal(main({ args: ['--root', tree()], ...failed, runInstall: installWriting(AFTER, 1) }), 1)
  assert.deepEqual(failed.err, ['- yarn install failed'])

  const drift = capture()
  const lockfile = AFTER.replace('  version: 19.2.8', '  version: 19.2.9')
  assert.equal(main({ args: ['--root', tree()], ...drift, runInstall: installWriting(lockfile) }), 1)
  assert.match(drift.err[0], /changed third-party resolutions/)
  assert.equal(drift.err[1], '- changed resolution "react@npm:19.2.8":')
})

test('runYarnInstall runs a mutable install in the repository root', () => {
  const calls = []
  const spawnSyncImpl = (command, args, options) => {
    calls.push({ command, args, options })
    return { status: calls.length === 1 ? 0 : null }
  }
  assert.equal(runYarnInstall({ rootDir: '/repo', spawnSyncImpl, platform: 'linux' }), 0)
  assert.equal(runYarnInstall({ rootDir: '/repo', spawnSyncImpl, platform: 'win32' }), 1)
  assert.deepEqual(calls[0].args, ['install', '--no-immutable'])
  assert.equal(calls[0].options.cwd, '/repo')
  assert.equal(calls[0].options.env.YARN_ENABLE_IMMUTABLE_INSTALLS, 'false')
  assert.equal(calls[0].options.shell, false)
  assert.equal(calls[1].options.shell, true)
})

test('linkPackagesNodeModules links packages/node_modules to the app once and never replaces anything else', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'enterprise-overlay-link-'))
  fs.mkdirSync(path.join(root, 'packages', 'app', 'node_modules'), { recursive: true })
  assert.equal(linkPackagesNodeModules(root, 'linux'), null)
  assert.equal(fs.readlinkSync(path.join(root, 'packages', 'node_modules')), 'app/node_modules')
  assert.equal(linkPackagesNodeModules(root), null)
  const windows = fs.mkdtempSync(path.join(os.tmpdir(), 'enterprise-overlay-link-'))
  fs.mkdirSync(path.join(windows, 'packages'), { recursive: true })
  assert.equal(linkPackagesNodeModules(windows, 'win32'), null)

  const other = fs.mkdtempSync(path.join(os.tmpdir(), 'enterprise-overlay-link-'))
  fs.mkdirSync(path.join(other, 'packages', 'node_modules'), { recursive: true })
  assert.equal(
    linkPackagesNodeModules(other),
    'packages/node_modules exists and is not a link to packages/app/node_modules',
  )
  const linkedElsewhere = fs.mkdtempSync(path.join(os.tmpdir(), 'enterprise-overlay-link-'))
  fs.mkdirSync(path.join(linkedElsewhere, 'packages'), { recursive: true })
  fs.symlinkSync('ui', path.join(linkedElsewhere, 'packages', 'node_modules'))
  assert.match(linkPackagesNodeModules(linkedElsewhere), /is not a link/)
})

test('main fails when packages/node_modules is something else', () => {
  const root = tree()
  fs.mkdirSync(path.join(root, 'packages', 'node_modules'))
  const io = capture()
  assert.equal(main({ args: ['--root', root, '--no-install'], ...io }), 1)
  assert.match(io.err[0], /is not a link/)
})
