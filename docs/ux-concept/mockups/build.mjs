// Builds app.js from app.ts without dependencies: Node >= 23.2 (module.stripTypeScriptTypes),
// i18n.js from i18n/*.json (UI catalogs) and logo.js from the club logo.
// Usage: node docs/ux-concept/mockups/build.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stripTypeScriptTypes } from 'node:module'

const dir = dirname(fileURLToPath(import.meta.url))
const banner = '// Generated by build.mjs — do not edit by hand.\n'

// UI catalogs: every i18n/<lang>.json must have exactly the same keys as en.json (the source catalog).
const i18nDir = join(dir, 'i18n')
const catalogs = {}
for (const f of readdirSync(i18nDir).filter((x) => x.endsWith('.json')).sort()) {
  const code = f.slice(0, -5)
  try { catalogs[code] = JSON.parse(readFileSync(join(i18nDir, f), 'utf8')) } catch (e) { console.error(`i18n/${f}: invalid JSON — ${e.message}`); process.exit(1) }
}
if (!catalogs.en) { console.error('i18n/en.json (source catalog) is missing'); process.exit(1) }
let failed = false
const enKeys = Object.keys(catalogs.en)
for (const [code, cat] of Object.entries(catalogs)) {
  if (!cat._meta || typeof cat._meta.name !== 'string') { console.error(`i18n/${code}.json: "_meta": { "name": … } is missing`); failed = true }
  if (code === 'en') continue
  const missing = enKeys.filter((k) => !(k in cat))
  const extra = Object.keys(cat).filter((k) => !(k in catalogs.en))
  if (missing.length) { console.error(`i18n/${code}.json: ${missing.length} key(s) missing (present in en.json):\n  ${missing.join('\n  ')}`); failed = true }
  if (extra.length) { console.error(`i18n/${code}.json: ${extra.length} key(s) not in en.json:\n  ${extra.join('\n  ')}`); failed = true }
}
// Plural values are objects selected by Intl.PluralRules; each needs at least the "other" (or "many") form.
for (const [code, cat] of Object.entries(catalogs)) {
  for (const [k, v] of Object.entries(cat)) {
    if (k === '_meta' || typeof v === 'string') continue
    if (!v || typeof v !== 'object' || !(typeof v.other === 'string' || typeof v.many === 'string')) { console.error(`i18n/${code}.json: "${k}" must be a string or a plural object with "other"/"many"`); failed = true }
  }
}
if (failed) { console.error('i18n: catalog check failed'); process.exit(1) }
writeFileSync(join(dir, 'i18n.js'), `${banner}window.VEREINO_I18N = ${JSON.stringify(catalogs)}\n`)
console.log('i18n.js:', Object.entries(catalogs).map(([c, cat]) => `${c} (${cat._meta.name}) ${Object.keys(cat).length - 1} keys`).join(', '))

const source = readFileSync(join(dir, 'app.ts'), 'utf8')
const js = stripTypeScriptTypes(source, { mode: 'strip' })
writeFileSync(join(dir, 'app.js'), banner + js)
console.log('app.js:', js.length, 'chars')

// Club logo: the first file found among logo-klubu.png|jpg|jpeg|webp → logo.js (data URI).
const types = { png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', webp: 'image/webp' }
const found = Object.keys(types).map((ext) => [ext, join(dir, `logo-klubu.${ext}`)]).find(([, f]) => existsSync(f))
const logo = found ? `data:${types[found[0]]};base64,${readFileSync(found[1]).toString('base64')}` : ''
writeFileSync(join(dir, 'logo.js'), `${banner}window.VEREINO_LOGO = ${JSON.stringify(logo)}\n`)
console.log('logo.js:', found ? `from ${found[1]}` : 'no logo-klubu.* file — sample star')
